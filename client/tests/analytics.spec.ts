import { test, expect } from '@playwright/test'

test('scan table shows real request metadata, supports filters, details and pagination on desktop/mobile', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const registration = await page.request.post('/api/users', { data: {
    name: 'Analytics', lastName: 'Tester', email: `analytics-${Date.now()}@example.test`, password: 'analytics test password',
  } })
  expect(registration.status()).toBe(201)
  const file = await (await page.request.post('/api/files', { data: { name: 'Analytics URL', type: 'web-url', url: 'https://example.com/analytics' } })).json()
  const result = await (await page.request.post('/api/products/create/', { data: { name: 'Tracked product', fileId: file._id } })).json()
  const code = await (await page.request.post('/api/qrcodes', { data: { name: 'Tracked QR', productId: result.product._id } })).json()
  const other = await (await page.request.post('/api/qrcodes', { data: { name: 'Unscanned QR', productId: result.product._id } })).json()
  for (let i = 0; i < 27; i++) {
    const scan = await page.request.get(`${code.url}?utm_source=newsletter&tag=one&tag=two&note=%3Cscript%3Eunsafe%3C%2Fscript%3E`, { maxRedirects: 0, headers: {
      'user-agent': 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36',
      'accept-language': 'en-GB,en;q=0.9', referer: 'https://example.com/launch',
    } })
    expect(scan.status()).toBe(302)
  }
  await expect.poll(async () => (await (await page.request.get('/api/statistics')).json()).length).toBe(27)
  await page.goto('/admin/analytics')
  await expect(page.getByRole('heading', { name: 'Scans over time' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'All scans', exact: true })).toHaveCount(0)
  await page.getByRole('navigation', { name: 'Analytics views' }).getByRole('link', { name: 'Scan details' }).click()
  await expect(page).toHaveURL(/tab=scans/)
  await expect(page.getByRole('heading', { name: 'Scans over time' })).toHaveCount(0)
  const table = page.getByRole('table', { name: /All recorded scans/ })
  await expect(table.locator('tbody tr')).toHaveCount(25)
  await expect(page.getByText('27 matching scans')).toBeVisible()
  await expect(table.locator('tbody tr').first()).toContainText('Tracked QR')
  await expect(table.locator('tbody tr').first()).toContainText('Chrome 130.0.0.0')
  await expect(table.locator('tbody tr').first()).toContainText('utm_source=newsletter')
  await expect(table.locator('tbody tr').first()).toContainText('tag=one')
  await expect(table.locator('tbody tr').first()).toContainText('tag=two')
  await expect(table.locator('tbody tr').first()).toContainText('<script>unsafe</script>')
  await page.getByRole('button', { name: 'Next scan page' }).click()
  await expect(table.locator('tbody tr')).toHaveCount(2)
  await page.getByRole('button', { name: 'Previous scan page' }).click()
  await table.getByRole('button', { name: /^View scan/ }).first().click()
  const details = page.getByRole('dialog')
  await expect(details.getByRole('heading', { name: 'Scan details' })).toBeVisible()
  await expect(details.getByRole('rowheader', { name: 'data.request.referrer', exact: true })).toBeVisible()
  await expect(details.getByText('https://example.com/launch', { exact: true })).toBeVisible()
  await expect(details.getByRole('rowheader', { name: 'data.fingerprint', exact: true })).toBeVisible()
  await expect(details.getByText('Unavailable', { exact: true }).first()).toBeVisible()
  await page.screenshot({ path: '/tmp/qr2share-scan-details.png', fullPage: true })
  await details.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByLabel('Search scans').fill('no-matching-value')
  await expect(page.getByText('No scans match these filters.')).toBeVisible()
  await page.getByRole('button', { name: 'Clear scan search', exact: true }).click()
  await expect(page.getByLabel('Search scans')).toHaveValue('')
  await page.getByLabel('Search scans').fill('newsletter')
  await expect(table.locator('tbody tr')).toHaveCount(25)
  await page.getByLabel('Filter scans by QR code').selectOption(other._id)
  await expect(page.getByText('0 matching scans')).toBeVisible()
  await page.getByLabel('Filter scans by QR code').selectOption(code._id)
  await expect(page.getByText('27 matching scans')).toBeVisible()
  await page.getByRole('button', { name: 'Refresh scans', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Refresh scans', exact: true })).toBeEnabled()
  await expect(page).toHaveURL(new RegExp(`qrCode=${code._id}`))
  await page.reload()
  await expect(page.getByLabel('Filter scans by QR code')).toHaveValue(code._id)
  await expect(table.locator('tbody tr')).toHaveCount(25)
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await expect(page.getByLabel('Filter scans by QR code')).toHaveValue('')
  await page.goto('/admin/qr-codes')
  await page.getByLabel('Actions for Tracked QR').click()
  await page.getByRole('link', { name: 'View scans', exact: true }).click()
  await expect(page.getByLabel('Filter scans by QR code')).toHaveValue(code._id)
  await expect(page.getByRole('heading', { name: 'Scans for Tracked QR', exact: true })).toBeVisible()
  await page.goto('/admin/qr-codes')
  await page.getByRole('button', { name: 'Tracked QR', exact: true }).click()
  await page.getByRole('dialog').getByRole('link', { name: 'View scans', exact: true }).click()
  await expect(page.getByLabel('Filter scans by QR code')).toHaveValue(code._id)
  await page.goto('/admin/qr-codes')
  await page.getByRole('link', { name: 'View scans for Unscanned QR', exact: true }).click()
  await expect(page.getByLabel('Filter scans by QR code')).toHaveValue(other._id)
  await expect(page.getByText('0 matching scans')).toBeVisible()
  await page.goBack()
  await page.getByRole('link', { name: 'View scans for Tracked QR', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(25)
  await page.screenshot({ path: '/tmp/qr2share-scan-table.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(table.locator('tbody tr')).toHaveCount(25)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('region', { name: 'Scan records table' }).evaluate(el => { el.scrollLeft = el.scrollWidth })
  await table.getByRole('button', { name: /^View scan/ }).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '/tmp/qr2share-mobile-scan-details.png', fullPage: true })
  expect(errors).toEqual([])
})
