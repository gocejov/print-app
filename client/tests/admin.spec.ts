test('product page editor publishes media and an action on desktop and mobile', async ({ page }) => {
  await register(page, 'ProductPage')
  await addUrlProduct(page, 'Gallery product', 'https://example.com/catalog')
  const png = await sharp({ create: { width: 640, height: 400, channels: 4, background: '#619b7f' } }).png().toBuffer()
  const user = await (await page.request.get('/api/users/me')).json()
  const users = Array.isArray(user) ? user : [user]
  const upload = await page.request.post(`/api/upload/image/${users[0]._id}`, {
    multipart: { name: 'Gallery image', image: { name: 'gallery.png', mimeType: 'image/png', buffer: png } },
  })
  expect(upload.ok(), await upload.text()).toBeTruthy()
  await page.reload()
  await page.getByRole('button', { name: 'Edit Gallery product', exact: true }).click()
  await page.getByLabel('Scan experience').selectOption('page')
  await page.getByRole('checkbox', { name: 'Gallery image' }).check()
  await page.getByLabel('Action button label').fill('Book a visit')
  await page.getByLabel('Action button URL').fill('https://example.com/book')
  await page.getByRole('button', { name: 'Save product', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const products = await (await page.request.get('/api/products/with-options')).json()
  const product = products.find((item: { name: string }) => item.name === 'Gallery product')
  expect(product.displayMode).toBe('page')
  const qrResponse = await page.request.post('/api/qrcodes', { data: { productId: product._id, name: 'Gallery QR' } })
  expect(qrResponse.ok()).toBeTruthy()
  const qr = await qrResponse.json()
  await page.goto(new URL(qr.url).pathname)
  await expect(page.getByRole('heading', { name: 'Gallery product' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Book a visit' })).toHaveAttribute('href', 'https://example.com/book')
  await expect(page.getByRole('img', { name: 'Gallery image' })).toBeVisible()
  expect(await page.getByRole('img').evaluate((image) => (image as HTMLImageElement).naturalWidth)).toBe(640)
  await page.screenshot({ path: '/tmp/qr2share-product-page-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('link', { name: 'Book a visit' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '/tmp/qr2share-product-page-mobile.png', fullPage: true })
})
