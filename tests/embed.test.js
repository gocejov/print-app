const { test } = require('node:test')
const assert = require('node:assert/strict')
const { publicAddress, embeddingHeadersAllow, canEmbed, embeddedPage } = require('../src/services/embed.service')

test('embedding probes reject private, loopback, metadata and reserved addresses', async () => {
  for (const address of ['127.0.0.1', '10.0.0.1', '172.16.2.1', '192.168.1.1', '169.254.169.254', '100.64.0.1', '0.0.0.0', '224.0.0.1', '::1', 'fc00::1', 'fe80::1', '::ffff:127.0.0.1', '2001:db8::1']) assert.equal(publicAddress(address), false, address)
  assert.equal(publicAddress('1.1.1.1'), true)
  assert.equal(publicAddress('2606:4700:4700::1111'), true)
  assert.equal(await canEmbed('http://127.0.0.1/', 'https://qr2share.com'), false)
  assert.equal(await canEmbed('http://169.254.169.254/', 'http://qr2share.com'), false)
  assert.equal(await canEmbed('https://qr2share.com/q/012345678901234567890123', 'https://qr2share.com'), false)
  assert.equal(await canEmbed('file:///etc/passwd', 'https://qr2share.com'), false)
  assert.equal(await canEmbed('https://example.com:8443/', 'https://qr2share.com'), false)
})

test('embedding headers respect CSP ancestors, XFO and conservative unsupported policies', () => {
  const destination = new URL('https://destination.example/page')
  const parent = new URL('https://qr2share.com')
  const allowed = headers => embeddingHeadersAllow(headers, destination, parent)
  assert.equal(allowed({}), true)
  assert.equal(allowed({ 'x-frame-options': 'DENY' }), false)
  assert.equal(allowed({ 'x-frame-options': 'SAMEORIGIN' }), false)
  assert.equal(embeddingHeadersAllow({ 'x-frame-options': 'SAMEORIGIN' }, parent, parent), true)
  assert.equal(allowed({ 'content-security-policy': "frame-ancestors 'none'" }), false)
  assert.equal(allowed({ 'content-security-policy': "default-src 'none'" }), true)
  assert.equal(allowed({ 'content-security-policy': "frame-ancestors 'self'" }), false)
  assert.equal(allowed({ 'content-security-policy': 'frame-ancestors https://qr2share.com' }), true)
  assert.equal(allowed({ 'content-security-policy': 'frame-ancestors https://qr2share.com.evil.test' }), false)
  assert.equal(allowed({ 'content-security-policy': "frame-ancestors https://qr2share.com, frame-ancestors 'none'" }), false)
  assert.equal(allowed({ 'content-security-policy': 'frame-ancestors *', 'x-frame-options': 'DENY' }), true)
  assert.equal(allowed({ 'content-security-policy': 'frame-ancestors https://*.example.com' }), false)
  const html = embeddedPage('https://example.com/?a=1&b="test"', '<unsafe>')
  assert.match(html, /&lt;unsafe&gt;/)
  assert.match(html, /sandbox=/)
  assert.doesNotMatch(html, /<unsafe>/)
})
